"""Linux acceptance: real Rust generator, actual BIRD parse, no network lab.

Run only in the dedicated source/build directory with its router binaries.
Existing output directories and reports are never overwritten.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def run(args):
    if args.report.exists():
        raise FileExistsError(args.report)
    root = args.root.resolve()
    generator = root / "target/release/sav_lab_gen"
    records, expected_configs, generated_hashes = [], 0, {}
    for scene in sorted(args.scenes.iterdir()):
        if not scene.is_dir():
            continue
        manifest = json.loads((scene / "manifest.json").read_text())
        for variant in ("savop-base.json", "savop-anycast.json"):
            source = scene / variant
            if sha(source) != manifest["artifacts"][variant]:
                raise ValueError("Input scene hash mismatch")
            data = json.loads(source.read_text())
            out = root / ("savop_run_policy_" + scene.name + ("_anycast" if "anycast" in variant else "_base"))
            result = subprocess.run([str(generator), "--config", str(source.resolve()), "--out", str(out)],
                                    cwd=root, text=True, capture_output=True)
            if result.returncode:
                raise RuntimeError(result.stdout + result.stderr)
            expected_roles = {}
            for e in data["routing_policy"]["links"]:
                a, b = e["a"], e["b"]
                if e["relationship"] == "p2p":
                    ra, rb = "peer", "peer"
                else:
                    ra, rb = ("provider", "customer") if e["provider"] == a else ("customer", "provider")
                expected_roles[(a, b)] = (ra, rb)
                expected_roles[(b, a)] = (rb, ra)
            for node in data["devices"]:
                config = json.loads((out / node / "sa.json").read_text())
                for link in config["link_map"].values():
                    if (link["local_role"], link["remote_role"]) != expected_roles[(node, link["remote_id"])]:
                        raise AssertionError("Generated Agent roles differ from explicit topology")
                bird = out / node / "bird.conf"
                generated_hashes[str(bird.relative_to(root))] = sha(bird)
                generated_hashes[str((out / node / "sa.json").relative_to(root))] = sha(out / node / "sa.json")
                expected_configs += 1
            records.append({"sample": scene.name, "variant": variant, "nodes": len(data["devices"]),
                            "generated": str(out), "input_sha256": sha(source), "stdout": result.stdout})
            print(f"Generated {scene.name} {variant}: {len(data['devices'])}", flush=True)
    if not records:
        raise ValueError("No scenes generated")
    # Only read configs generated by this tool in this dedicated root.
    # No BGP sockets, network namespaces, filtering or external traffic are started.
    script = 'set -eu; count=0; for cfg in /work/savop_run_policy_*/*/bird.conf; do /work/router/bird -p -c "$cfg"; count=$((count+1)); done; printf "PARSED=%s\\n" "$count"'
    result = subprocess.run(["docker", "run", "--rm", "--network", "none", "--read-only",
                             "--mount", f"type=bind,source={root},target=/work,readonly",
                             "--entrypoint", "/bin/sh", "savop_runtime_clab:latest", "-c", script],
                            text=True, capture_output=True)
    if result.returncode or f"PARSED={expected_configs}" not in result.stdout.splitlines():
        raise RuntimeError("Actual BIRD parse failed: " + result.stdout + result.stderr)
    report = {"status": "generated_and_bird_parsed_not_deployed", "generated_node_configs": expected_configs,
              "records": records, "generated_sha256": generated_hashes,
              "generator_sha256": sha(generator), "bird_sha256": sha(root / "router/bird"),
              "verifier_sha256": sha(Path(__file__)), "parse_stdout": result.stdout,
              "parse_stderr": result.stderr, "not_verified": ["routing convergence", "route leaks", "packet filtering", "scale performance"]}
    with args.report.open("x") as f:
        json.dump(report, f, indent=2)
    print(json.dumps({k: report[k] for k in ("status", "generated_node_configs")}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True)
    parser.add_argument("--scenes", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    run(parser.parse_args())
